# Paths stripped from repo_diff output — never source files, only generated artifacts.
# Directory prefixes: any file under these dirs is excluded.
_DIFF_EXCLUDE_PREFIXES = ("node_modules/", "vendor/", ".venv/", "__pycache__/")
# Exact filenames: lock files are auto-generated by package managers, not by the coder.
_DIFF_EXCLUDE_FILES = frozenset({"package-lock.json", "yarn.lock", "pnpm-lock.yaml"})


def _filter_diff(diff: str) -> str:
    """Remove diff sections for generated/dependency directories and lock files."""
    if not diff:
        return diff
    sections: list[str] = []
    current: list[str] = []
    skip = False
    for line in diff.splitlines(keepends=True):
        if line.startswith("diff --git "):
            if current and not skip:
                sections.extend(current)
            current = [line]
            parts = line.split(" b/", 1)
            path = parts[1].strip().strip('"') if len(parts) == 2 else ""
            skip = path.startswith(_DIFF_EXCLUDE_PREFIXES) or path in _DIFF_EXCLUDE_FILES
        else:
            current.append(line)
    if current and not skip:
        sections.extend(current)
    return "".join(sections)



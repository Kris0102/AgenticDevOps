class DockerSandboxTools:
    """
    A thin tool implementation layer over Docker.

    You can later expose these as MCP tools:
      - sandbox.create
      - sandbox.exec
      - sandbox.put_file
      - fs.read_file
      - fs.write_file
      - repo.diff
    """

    def __init__(
        self,
        image: str,
        workdir: str = "/workspace",
        cpu_quota: Optional[int] = None,
        mem_limit: Optional[str] = None,
        network_mode: Optional[str] = None,
        labels_base: Optional[Dict[str, str]] = None,
        path_prepend: Optional[str] = None,
        repo_dir: str = "repo",
    ) -> None:
        self.image = image
        self.workdir = workdir
        # Subdirectory of `workdir` holding the repo; "" means the repo IS `workdir` (a
        # pre-provisioned image checks out straight into it). Carried here so `repo_diff` and
        # the gateway derive the working directory instead of assuming `<workdir>/repo` —
        # assuming it made every command run in a nonexistent `/testbed/repo` (ADR 0039).
        self.repo_dir = repo_dir
        self.cpu_quota = cpu_quota
        self.mem_limit = mem_limit
        self.network_mode = network_mode  # e.g. "none" for no network
        self.labels_base = labels_base or {}
        # Prepended to the image's own PATH at container creation, so EVERY exec — including
        # ones that pass no `env` — resolves an in-image interpreter (conda env, venv) first.
        self.path_prepend = path_prepend
        self.client = docker.from_env()

    @property
    def workspace_path(self) -> str:
        """Absolute path of the repo inside the container — the cwd for repo commands."""
        return self._join(self.repo_dir)

    def _join(self, repo_dir: str) -> str:
        return f"{self.workdir}/{repo_dir}" if repo_dir else self.workdir

    def _container_env(self) -> Optional[List[str]]:
        """Container environment for creation. Resolves the IMAGE's real PATH and prepends
        `path_prepend` to it, rather than assuming a default — a wrong PATH silently breaks
        every command in the container, so it is read from the image config."""
        if not self.path_prepend:
            return None
        base_path = ""
        try:
            for entry in self.client.images.get(self.image).attrs["Config"]["Env"] or []:
                if entry.startswith("PATH="):
                    base_path = entry[len("PATH="):]
                    break
        except Exception as exc:  # noqa: BLE001 — fall back to a sane default, but say so
            _log.warning("sandbox.image_path_unreadable", image=self.image, error=str(exc))
        if not base_path:
            base_path = "/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
        return [f"PATH={self.path_prepend}:{base_path}"]

    # ---- lifecycle ----s
    def get_sandbox_id(self, *, run_id: str, verify: bool = True) -> str:
        if verify:
            with db.session_scope() as session:
                record = session.get(Sandbox, f"sbox_{run_id}")
                if not record:
                    raise SandboxError(f"Unknown run_id: {run_id}. Did you call sandbox.create?")
        return f"sbox_{run_id}"
    
    def sandbox_create(self, *, run_id: str) -> SandboxCreateResult:
        """
        Create a container per run. Idempotent: reconnects to existing container if DB record exists.
        """
        sandbox_id = f"sbox_{run_id}"

        with db.session_scope() as session:
            existing = session.get(Sandbox, sandbox_id)
            if existing:
                cid = existing.container_id
                _log.debug("sandbox.exists_checking", sandbox_id=sandbox_id, container=cid[:12])
                try:
                    container = self.client.containers.get(cid)
                except docker_errors.NotFound:
                    container = None
                if container is not None:
                    if container.status != "running":
                        container.start()
                    _log.info("sandbox.reconnected", sandbox_id=sandbox_id,
                              container=cid[:12], status=container.status)
                    return SandboxCreateResult(sandbox_id=sandbox_id, container_id=cid)
                _log.warning("sandbox.container_gone", sandbox_id=sandbox_id, container=cid[:12],
                             action="recreating registry entry")
                session.delete(existing)

        # The DB record may be missing (e.g. after a DB wipe) while the named container
        # still exists in Docker — reconnect to it instead of letting `containers.run`
        # raise a 409 name conflict.
        try:
            container = self.client.containers.get(sandbox_id)
        except docker_errors.NotFound:
            container = None

        if container is not None:
            if container.status != "running":
                container.start()
            container_id = container.id or ""
            _log.info("sandbox.reregistering_untracked", sandbox_id=sandbox_id,
                      container=container_id[:12], status=container.status)
            with db.session_scope() as session:
                session.merge(Sandbox(sandbox_id=sandbox_id, run_id=run_id, container_id=container_id))
            return SandboxCreateResult(sandbox_id=sandbox_id, container_id=container_id)

        labels = dict(self.labels_base)
        labels.update({"agentic.run_id": run_id, "agentic.sandbox_id": sandbox_id})
        
        try:
            container = self.client.containers.run(
                self.image,
                name=sandbox_id,
                command=["sleep", "infinity"],
                detach=True,
                working_dir=self.workdir,
                labels=labels,
                network_mode=self.network_mode,
                mem_limit=self.mem_limit,
                cpu_quota=self.cpu_quota,
                environment=self._container_env(),
                # Override any ENTRYPOINT the image declares. Without this, an image built
                # with e.g. `ENTRYPOINT ["python"]` turns our keep-alive into
                # `python sleep infinity`: the container exits instantly and every later
                # exec fails against a dead container. A no-op for images that declare no
                # entrypoint (both of ours) — it matters only now that a user-supplied image
                # can be named. Verified against a purpose-built ENTRYPOINT image.
                entrypoint=[],
            )

            container.exec_run(cmd=["mkdir", "-p", self.workdir], workdir="/")
        except Exception as exc:
            _log.error("sandbox.create_failed", sandbox_id=sandbox_id, error=str(exc))
            raise SandboxError(f"sandbox.create failed: {exc}")
            

        container_id = container.id or ""
        with db.session_scope() as session:
            session.add(Sandbox(sandbox_id=sandbox_id, run_id=run_id, container_id=container_id))

        return SandboxCreateResult(sandbox_id=sandbox_id, container_id=container_id)

    def sandbox_destroy(self, *, sandbox_id: str) -> None:
        with db.session_scope() as session:
            record = session.get(Sandbox, sandbox_id)
            if not record:
                return
            cid = record.container_id
            run_id = record.run_id
            session.delete(record)

        # Workspace semantic chunks are run-local — purge them with the sandbox so
        # they never outlive the container. Best-effort (non-fatal).
        try:
            from db.semanticMemory.semantic_store import SemanticStore

            removed = SemanticStore().delete_workspace(run_id)
            _log.info("sandbox.workspace_chunks_purged", run_id=run_id, removed=removed)
        except Exception as e:
            _log.warning("sandbox.workspace_purge_failed", run_id=run_id, error=str(e))

        try:
            c = self.client.containers.get(cid)
            try:
                c.kill()
            except Exception:
                pass
            c.remove(force=True)
        except Exception:
            pass
    
    def sandbox_exists(self, *, sandbox_id: str, start_if_created_but_not_running: bool = False) -> bool:
        with db.session_scope() as session:
            record = session.get(Sandbox, sandbox_id)
            if not record:
                return False
            cid = record.container_id
        try:
            c = self.client.containers.get(cid)
            if start_if_created_but_not_running and c.status == "created":
                c.start()
            return c.status == "running" or c.status == "created" 
        except Exception:
            return False
        
    def sanxbox_stop_container(self, *, sandbox_id: str) -> None:
        _log.info("sandbox.stop_container", sandbox_id=sandbox_id)
        with db.session_scope() as session:
            record = session.get(Sandbox, sandbox_id)
            if not record:
                return
            cid = record.container_id
            
        try:
            c = self.client.containers.get(cid)
            try:
                if c.status == "running":
                    c.stop(timeout=5)  
                    _log.info("sandbox.stop_container_success", sandbox_id=sandbox_id, container_id=cid)
            except Exception:
                _log.warning("sandbox.stop_container_failed", sandbox_id=sandbox_id, container_id=cid)
                pass
        except Exception:
            pass
          
    # ---- core exec ----

    def sandbox_exec(
        self,
        *,
        sandbox_id: str,
        cmd: List[str],
        timeout_s: int,
        cwd: str,
        env: Optional[Dict[str, str]] = None,
    ) -> ExecResult:
        """
        Execute cmd (array form) inside container. No shell.
        """
        cid = self._require_container_id(sandbox_id)
        container = self.client.containers.get(cid)

        start = time.time()
        # Enforce timeout_s. `docker exec` (exec_run) has NO process-kill timeout — it blocks
        # until the command exits — so a hanging command (a synth test with a live setInterval,
        # an infinite loop, a server that listen()s, a stalled install) used to freeze the whole
        # run FOREVER with no recovery but a manual kill. Wrap in coreutils `timeout` (always in
        # the Debian base image): it SIGTERMs the command at timeout_s, then SIGKILLs 5s later if
        # it ignores TERM. The wrapped process then exits 124 (or 137 if it needed the KILL) —
        # callers classify those as a harness ERROR, never a code verdict.
        wrapped = ["timeout", "--kill-after=5", str(timeout_s), *cmd]
        res = container.exec_run(
            cmd=wrapped,
            workdir=cwd,
            environment=env,
            demux=True,  # returns (stdout, stderr)
        )
        duration_ms = int((time.time() - start) * 1000)

        exit_code = int(res.exit_code) if res.exit_code is not None else 1
        stdout_b, stderr_b = res.output if res.output is not None else (b"", b"")
        stdout = (stdout_b or b"").decode("utf-8", errors="replace")
        stderr = (stderr_b or b"").decode("utf-8", errors="replace")

        # Make a watchdog kill self-describing so it reads as "harness stopped it", not a silent
        # negative. 124 = timeout fired; 137 = 128+SIGKILL (ignored TERM, got --kill-after).
        if exit_code in (124, 137):
            note = f"[sandbox watchdog] command exceeded {timeout_s}s and was killed (exit {exit_code})"
            stderr = f"{stderr}\n{note}".strip() if stderr else note

        return ExecResult(exit_code=exit_code, stdout=stdout, stderr=stderr, duration_ms=duration_ms)

    # ---- Git helpers (still using exec) ----
    # clone/checkout + branch/commit/push moved to gitops.GitOps (the GitHub boundary,
    # ADR 0012). `repo_diff` stays here — it's local working-tree inspection the coder
    # uses for grounded verification, not a remote/GitHub operation.

    def repo_diff(self, *, sandbox_id: str, repo_dir: Optional[str] = None) -> str:
        diff = self.sandbox_exec(
            sandbox_id=sandbox_id,
            cmd=["git", "diff"],
            timeout_s=60,
            cwd=self.workspace_path if repo_dir is None else self._join(repo_dir),
        )
        return _filter_diff(diff.stdout)
    

from datetime import datetime, timezone
from typing import Any, Optional
from sqlalchemy import BigInteger, DateTime, Identity, Index, Integer, JSON, String, Text
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column
from pgvector.sqlalchemy import Vector


# Embedding dimension for all-MiniLM-L6-v2 (see db/embedder.py). Keep in sync with
# the Vector(...) column on CodeChunk and the migration that creates code_chunks.
EMBEDDING_DIM = 384


class Base(DeclarativeBase):
    pass


class Run(Base):
    __tablename__ = "runs"

    run_id: Mapped[str] = mapped_column(String, primary_key=True)
    repo_url: Mapped[str] = mapped_column(String, nullable=False)
    base_sha: Mapped[Optional[str]] = mapped_column(String, nullable=True)
    status: Mapped[str] = mapped_column(String, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc))
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), onupdate=lambda: datetime.now(timezone.utc))


class Event(Base):
    __tablename__ = "events"
    # (run_id, seq) is the live-tail / timeline cursor: WHERE run_id=? AND seq>?
    __table_args__ = (Index("ix_events_run_id_seq", "run_id", "seq"),)

    event_id: Mapped[str] = mapped_column(String, primary_key=True)
    run_id: Mapped[str] = mapped_column(String, nullable=False, index=True)
    ts: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), index=True)
    actor: Mapped[str] = mapped_column(String, nullable=False)
    event_type: Mapped[str] = mapped_column(String, nullable=False, index=True)
    payload_json: Mapped[dict] = mapped_column(JSON, nullable=False)
    # DB-assigned monotonic sequence — the SSE event id + replay cursor. Postgres
    # GENERATED BY DEFAULT AS IDENTITY; ts alone is collision-prone as a cursor.
    seq: Mapped[int] = mapped_column(BigInteger, Identity(always=False), nullable=False)


class Sandbox(Base):
    __tablename__ = "sandboxes"

    sandbox_id: Mapped[str] = mapped_column(String, primary_key=True)
    run_id: Mapped[str] = mapped_column(String, nullable=False, index=True)
    container_id: Mapped[str] = mapped_column(String, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc))


class Artifact(Base):
    __tablename__ = "artifacts"

    artifact_id: Mapped[str] = mapped_column(String, primary_key=True)
    run_id: Mapped[str] = mapped_column(String, nullable=False, index=True)
    kind: Mapped[str] = mapped_column(String, nullable=False)
    content_text: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    sha256: Mapped[Optional[str]] = mapped_column(String, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc))


class MicrotaskRecord(Base):
    """Persistent record of each microtask produced by the Planner."""
    __tablename__ = "microtasks"

    microtask_id: Mapped[str] = mapped_column(String, primary_key=True)
    run_id: Mapped[str] = mapped_column(String, nullable=False, index=True)
    idx: Mapped[int] = mapped_column(Integer, nullable=False)
    title: Mapped[str] = mapped_column(String, nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)
    approach: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    status: Mapped[str] = mapped_column(String, nullable=False, default="PENDING")
    attempts: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    acceptance_criteria: Mapped[Optional[Any]] = mapped_column(JSON, nullable=True)
    target_files: Mapped[Optional[Any]] = mapped_column(JSON, nullable=True)
    context_files: Mapped[Optional[Any]] = mapped_column(JSON, nullable=True)
    dependencies: Mapped[Optional[Any]] = mapped_column(JSON, nullable=True)
    files_touched: Mapped[Optional[Any]] = mapped_column(JSON, nullable=True)
    test_strategy: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc))
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), onupdate=lambda: datetime.now(timezone.utc))


class CodeChunk(Base):
    """A single AST-aligned slice of repository code, embedded for semantic search.

    Two namespaces (ARCHITECTURE_preview.md §4.2):
      - 'baseline'  — repo @ git_sha, ingested once at run start, shared across runs
      - 'workspace' — run-local edits, scoped by run_id, purged on teardown
    Search/retrieval only — never used to reconstruct the repo (Sandbox stays the
    source of truth). No FK constraints; run_id indexed (mirrors MicrotaskRecord).
    """
    __tablename__ = "code_chunks"

    chunk_id: Mapped[str] = mapped_column(String, primary_key=True)
    namespace: Mapped[str] = mapped_column(String, nullable=False, index=True)
    run_id: Mapped[Optional[str]] = mapped_column(String, nullable=True, index=True)
    repo_url: Mapped[str] = mapped_column(String, nullable=False, index=True)
    git_sha: Mapped[Optional[str]] = mapped_column(String, nullable=True)
    filepath: Mapped[str] = mapped_column(String, nullable=False)
    symbol: Mapped[Optional[str]] = mapped_column(String, nullable=True)
    chunk_type: Mapped[str] = mapped_column(String, nullable=False)
    chunk_text: Mapped[str] = mapped_column(Text, nullable=False)
    embedding: Mapped[Any] = mapped_column(Vector(EMBEDDING_DIM), nullable=False)
    metadata_json: Mapped[Optional[Any]] = mapped_column(JSON, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc))
